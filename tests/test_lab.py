"""WT-54 / P2-03: scan the running lab and compare it with lab/inventory.yaml by MAC.

The live test is marked ``lab`` and runs inside the scanner container (it needs
Nmap and the lab network). The comparison function has fast unit tests that
run in the normal CI job, with no Docker.
"""

import os
from pathlib import Path
from typing import Any

import pytest
import yaml

from watchtower.scanner.models import Host, Port, ScanResult
from watchtower.scanner.nmap_parser import parse_nmap_xml

ROOT = Path(__file__).resolve().parents[1]
LAB_NETWORK = "172.28.0.0/24"
SCANNER_IP = "172.28.0.20"
FULL_INVENTORY_XML = ROOT / "tests" / "fixtures" / "lab-full-inventory.xml"

# Docker's bridge gateway answers scans but is not a lab device. Its MAC is
# generated by Docker, so it cannot go in the inventory.
IGNORED_IPS = frozenset({"172.28.0.1"})


def compare_scan_to_inventory(result: ScanResult, devices: list[dict[str, Any]]) -> list[str]:
    """Return plain-English problems. An empty list means the lab matches."""
    expected = {d["mac"].lower(): set(d["ports"]) for d in devices}
    names = {d["mac"].lower(): d["name"] for d in devices}
    found: dict[str, set[int]] = {}
    problems: list[str] = []

    for host in result.hosts:
        if host.ip in IGNORED_IPS:
            continue
        if not host.mac:
            problems.append(f"unexpected host {host.ip} (no MAC)")
            continue
        found[host.mac.lower()] = {
            p.port for p in host.ports if p.protocol == "tcp" and p.state == "open"
        }

    for mac in sorted(expected.keys() - found.keys()):
        problems.append(f"missing device {names[mac]} ({mac})")
    for mac in sorted(found.keys() - expected.keys()):
        problems.append(f"unexpected device {mac}")
    for mac in sorted(expected.keys() & found.keys()):
        for port in sorted(expected[mac] - found[mac]):
            problems.append(f"{names[mac]}: expected port {port} is not open")
        for port in sorted(found[mac] - expected[mac]):
            problems.append(f"{names[mac]}: unexpected open port {port}")
    return problems


def _load_devices() -> list[dict[str, Any]]:
    data = yaml.safe_load((ROOT / "lab" / "inventory.yaml").read_text(encoding="utf-8"))
    return data["devices"]


@pytest.mark.lab
def test_inventory_fixture_matches_inventory() -> None:
    result = ScanResult.from_dict(parse_nmap_xml(FULL_INVENTORY_XML, profile="full"))
    problems = compare_scan_to_inventory(result, _load_devices())
    assert not problems, "\n".join(problems)


# --- Live lab tests (WT-54, Stage 2 gate): scan the running lab for real ---


@pytest.fixture(scope="module")
def live_full_scan() -> ScanResult:
    """One real full scan of the lab from the scanner container, shared by the tests below."""
    if os.environ.get("WATCHTOWER_CONFIG") != "/workspace/lab/watchtower.dev.toml":
        pytest.skip("live lab test: runs only inside the scanner container (CI lab job)")
    from watchtower.scanner.guardrail import scan_scope
    from watchtower.scanner.scan_engine import NmapEngine

    network, own_ip = scan_scope("eth0")  # the target comes from our own interface (WT-74)
    assert str(network) == LAB_NETWORK, f"scanner is not on the lab network: {network}"
    return NmapEngine(exclude_ip=str(own_ip)).run("full", str(network))


@pytest.mark.lab
def test_live_full_scan_matches_inventory(live_full_scan: ScanResult) -> None:
    problems = compare_scan_to_inventory(live_full_scan, _load_devices())
    assert not problems, "\n".join(problems)


@pytest.mark.lab
def test_live_watchtower_scan_raises_every_planted_risk(
    live_full_scan: ScanResult, tmp_path: Path
) -> None:
    """Milestone M2: the scan > identify > rules > store pipeline on the real lab."""
    from watchtower.cli import main
    from watchtower.pipeline import run_scan

    class _Replay:  # reuse the scan above instead of scanning the lab a second time
        def run(self, profile: str, target: str) -> ScanResult:
            return live_full_scan

    db = tmp_path / "lab.db"
    assert main(["consent", "--i-own-this-network", "--db", str(db)]) == 0  # WT-75
    report = run_scan(_Replay(), "full", LAB_NETWORK, db)
    found = {(d.mac or "").lower(): {f.rule_id for f in d.findings} for d in report.devices}
    problems = []
    for device in _load_devices():
        got = found.get(device["mac"].lower(), set())
        if got != set(device["expected_findings"]):
            problems.append(
                f"{device['name']}: expected {device['expected_findings']}, got {sorted(got)}"
            )
    assert not problems, "\n".join(problems)


# --- Unit tests for the test itself ---

DEVICES = [{"name": "router", "mac": "50:c7:bf:11:00:02", "ports": [53, 80]}]


def _scan(*hosts: Host) -> ScanResult:
    from datetime import UTC, datetime

    now = datetime(2026, 11, 20, tzinfo=UTC)
    return ScanResult("t", "full", LAB_NETWORK, now, now, "7.95", list(hosts))


def _host(ip: str, mac: str | None, ports: list[int]) -> Host:
    return Host(ip=ip, mac=mac, ports=[Port(p, "tcp", "open") for p in ports])


def test_matching_lab_has_no_problems() -> None:
    scan = _scan(_host("172.28.0.2", "50:C7:BF:11:00:02", [53, 80]))
    assert compare_scan_to_inventory(scan, DEVICES) == []


def test_missing_port_is_reported() -> None:
    scan = _scan(_host("172.28.0.2", "50:C7:BF:11:00:02", [53]))
    assert compare_scan_to_inventory(scan, DEVICES) == ["router: expected port 80 is not open"]


def test_extra_port_and_extra_device_are_reported() -> None:
    scan = _scan(
        _host("172.28.0.2", "50:C7:BF:11:00:02", [53, 80, 8080]),
        _host("172.28.0.99", "AA:BB:CC:DD:EE:FF", []),
    )
    problems = compare_scan_to_inventory(scan, DEVICES)
    assert "router: unexpected open port 8080" in problems
    assert "unexpected device aa:bb:cc:dd:ee:ff" in problems


def test_missing_device_is_reported() -> None:
    assert compare_scan_to_inventory(_scan(), DEVICES) == [
        "missing device router (50:c7:bf:11:00:02)"
    ]


def test_gateway_is_ignored() -> None:
    scan = _scan(
        _host("172.28.0.1", "CA:37:7F:86:EE:DD", [111]),
        _host("172.28.0.2", "50:C7:BF:11:00:02", [53, 80]),
    )
    assert compare_scan_to_inventory(scan, DEVICES) == []
